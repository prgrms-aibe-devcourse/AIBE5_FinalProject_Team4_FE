// 카테고리 매핑 함수
const mapCategory = (category: string): "Top" | "Bottom" | "Outer" | "Shoes" => {
    switch (category) {
        case "TOP": return "Top";
        case "BOTTOM": return "Bottom";
        case "OUTER": return "Outer";
        case "SHOES": return "Shoes";
        default: return "Top";
    }
};

// 색상 코드에서 색상 이름 가져오기
const getColorLabel = (colorCode: string): string => {
    const color = GARMENT_COLORS.find(c => c.code === colorCode);
    return color ? color.name : colorCode;
};

